/* =========================================================
   HELPERS
========================================================= */

function decodeSlug(slug: string) {
  try {
    return decodeURIComponent(slug);
  } catch {
    return slug;
  }
}

function absoluteUrl(path: string) {
  if (!path) {
    return BASE_URL;
  }

  if (
    path.startsWith("http://") ||
    path.startsWith("https://")
  ) {
    return path;
  }

  return `${BASE_URL}${
    path.startsWith("/") ? path : `/${path}`
  }`;
}

function formatDate(date: string | null) {
  if (!date) {
    return "";
  }

  try {
    return new Intl.DateTimeFormat("en-IN", {
      year: "numeric",
      month: "long",
      day: "numeric",
    }).format(new Date(date));
  } catch {
    return "";
  }
}

function normalizeText(value: unknown) {
  if (typeof value !== "string") {
    return "";
  }

  return value.trim();
}

/* =========================================================
   RICH TEXT SANITIZATION
========================================================= */

/*
 * The admin editor stores formatted text as HTML.
 *
 * We deliberately allow only a small set of formatting tags
 * and safe attributes.
 *
 * This protects the reader page from arbitrary scripts or
 * dangerous HTML being stored in the database.
 */

function sanitizeRichText(html: string) {
  if (!html) {
    return "";
  }

  /*
   * Server-side sanitization without requiring another
   * dependency.
   *
   * First remove dangerous tags completely.
   */

  let safe = html
    .replace(
      /<(script|style|iframe|object|embed|form|input|button|textarea|select|option|link|meta|base|svg|math)[^>]*>[\s\S]*?<\/\1>/gi,
      ""
    )
    .replace(
      /<(script|style|iframe|object|embed|form|input|button|textarea|select|option|link|meta|base|svg|math)[^>]*\/?>/gi,
      ""
    );

  /*
   * Remove event handlers such as:
   *
   * onclick=""
   * onerror=""
   * onmouseover=""
   */

  safe = safe.replace(
    /\s+on[a-z]+\s*=\s*(?:"[^"]*"|'[^']*'|[^\s>]+)/gi,
    ""
  );

  /*
   * Remove javascript: URLs.
   */

  safe = safe.replace(
    /\s+(href|src)\s*=\s*(["'])\s*javascript:[\s\S]*?\2/gi,
    ""
  );

  /*
   * Remove dangerous data URLs.
   */

  safe = safe.replace(
    /\s+(href|src)\s*=\s*(["'])\s*data:[\s\S]*?\2/gi,
    ""
  );

  /*
   * Keep the formatting elements generated by the editor.
   */

  const allowedTags = [
    "p",
    "br",
    "strong",
    "b",
    "em",
    "i",
    "u",
    "s",
    "strike",
    "del",
    "mark",
    "span",
    "a",
    "ul",
    "ol",
    "li",
    "blockquote",
    "h2",
    "h3",
    "h4",
  ];

  /*
   * Remove tags that are not in the allowed list while keeping
   * their text content.
   */

  safe = safe.replace(
    /<\/?([a-z0-9]+)(?:\s[^>]*)?>/gi,
    (match, tagName: string) => {
      const tag = tagName.toLowerCase();

      if (allowedTags.includes(tag)) {
        return match;
      }

      return "";
    }
  );

  /*
   * Sanitize attributes.
   *
   * For links we allow:
   * - href
   * - target
   * - rel
   * - title
   *
   * For span/mark we allow style only for the small set of
   * formatting properties used by the editor.
   */

  safe = safe.replace(
    /<([a-z0-9]+)(\s[^>]*)?>/gi,
    (fullMatch, tagName: string, attributeString = "") => {
      const tag = tagName.toLowerCase();

      if (!allowedTags.includes(tag)) {
        return "";
      }

      if (tag === "br") {
        return "<br />";
      }

      if (
        tag === "strong" ||
        tag === "b" ||
        tag === "em" ||
        tag === "i" ||
        tag === "u" ||
        tag === "s" ||
        tag === "strike" ||
        tag === "del" ||
        tag === "p" ||
        tag === "li" ||
        tag === "ul" ||
        tag === "ol" ||
        tag === "blockquote" ||
        tag === "h2" ||
        tag === "h3" ||
        tag === "h4"
      ) {
        return `<${tag}>`;
      }

      if (tag === "a") {
        const hrefMatch = attributeString.match(
          /href\s*=\s*(["'])(.*?)\1/i
        );

        const targetMatch = attributeString.match(
          /target\s*=\s*(["'])(.*?)\1/i
        );

        const relMatch = attributeString.match(
          /rel\s*=\s*(["'])(.*?)\1/i
        );

        const titleMatch = attributeString.match(
          /title\s*=\s*(["'])(.*?)\1/i
        );

        const href = hrefMatch?.[2] || "";

        /*
         * Only allow normal web URLs or internal relative URLs.
         */

        const safeHref =
          href.startsWith("/") ||
          href.startsWith("#") ||
          href.startsWith("https://") ||
          href.startsWith("http://") ||
          href.startsWith("mailto:")
            ? href
            : "#";

        const target = targetMatch?.[2];

        const rel =
          relMatch?.[2] ||
          (target === "_blank"
            ? "noopener noreferrer"
            : undefined);

        const title = titleMatch?.[2];

        const attributes = [
          `href="${escapeHtmlAttribute(safeHref)}"`,
          target
            ? `target="${escapeHtmlAttribute(target)}"`
            : "",
          rel
            ? `rel="${escapeHtmlAttribute(rel)}"`
            : "",
          title
            ? `title="${escapeHtmlAttribute(title)}"`
            : "",
        ]
          .filter(Boolean)
          .join(" ");

        return `<a ${attributes}>`;
      }

      if (
        tag === "span" ||
        tag === "mark"
      ) {
        const styleMatch = attributeString.match(
          /style\s*=\s*(["'])(.*?)\1/i
        );

        if (!styleMatch) {
          return `<${tag}>`;
        }

        const safeStyle =
          sanitizeInlineStyle(styleMatch[2]);

        return safeStyle
          ? `<${tag} style="${escapeHtmlAttribute(
              safeStyle
            )}">`
          : `<${tag}>`;
      }

      return `<${tag}>`;
    }
  );

  return safe;
}

function escapeHtmlAttribute(value: string) {
  return value
    .replace(/&/g, "&amp;")
    .replace(/"/g, "&quot;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function sanitizeInlineStyle(style: string) {
  /*
   * Only permit the formatting properties used by the editor.
   */

  const declarations = style
    .split(";")
    .map((item) => item.trim())
    .filter(Boolean);

  const allowedProperties = [
    "color",
    "background-color",
    "text-decoration",
  ];

  const safeDeclarations: string[] = [];

  for (const declaration of declarations) {
    const colonIndex = declaration.indexOf(":");

    if (colonIndex === -1) {
      continue;
    }

    const property = declaration
      .slice(0, colonIndex)
      .trim()
      .toLowerCase();

    const value = declaration
      .slice(colonIndex + 1)
      .trim();

    if (!allowedProperties.includes(property)) {
      continue;
    }

    /*
     * Prevent CSS functions that can be abused for URLs or
     * external resources.
     */

    if (
      /url\s*\(/i.test(value) ||
      /expression\s*\(/i.test(value) ||
      /javascript:/i.test(value)
    ) {
      continue;
    }

    safeDeclarations.push(
      `${property}: ${value}`
    );
  }

  return safeDeclarations.join("; ");
}

/* =========================================================
   DETECT RICH TEXT
========================================================= */

function containsHtml(value: string) {
  return /<\/?[a-z][\s\S]*>/i.test(value);
}

/* =========================================================
   RENDER RICH TEXT
========================================================= */

function RichText({
  html,
  className = "",
}: {
  html: string;
  className?: string;
}) {
  const safeHtml = sanitizeRichText(html);

  if (!safeHtml) {
    return null;
  }

  return (
    <div
      className={className}
      dangerouslySetInnerHTML={{
        __html: safeHtml,
      }}
    />
  );
}

/* =========================================================
   FETCH BLOG
========================================================= */

async function fetchBlog(
  slug: string
): Promise<Blog | null> {
  const decodedSlug = decodeSlug(slug);

  const { data, error } = await supabase
    .from("blogs")
    .select(`
      id,
      title,
      slug,
      excerpt,
      introduction,
      cover_image,
      category,
      author,
      tags,
      content_blocks,
      faqs,
      published,
      featured,
      views,
      meta_title,
      meta_description,
      published_at,
      created_at,
      updated_at
    `)
    .eq("slug", decodedSlug)
    .eq("published", true)
    .maybeSingle();

  if (error) {
    console.error(
      "Failed to fetch blog:",
      error.message
    );

    return null;
  }

  return data as Blog | null;
}

/* =========================================================
   CACHED BLOG FETCH
========================================================= */

async function getBlog(slug: string) {
  const decodedSlug = decodeSlug(slug);

  const cachedFetch = unstable_cache(
    async () => fetchBlog(decodedSlug),
    ["blog", decodedSlug],
    {
      revalidate: 60,
      tags: [
        "blogs",
        `blog-${decodedSlug}`,
      ],
    }
  );

  return cachedFetch();
}

/* =========================================================
   RELATED BLOGS
========================================================= */

async function getRelatedBlogs(
  blog: Blog
) {
  if (!blog.category) {
    return [];
  }

  try {
    const { data, error } =
      await supabase
        .from("blogs")
        .select(`
          id,
          title,
          slug,
          excerpt,
          cover_image,
          category,
          published_at
        `)
        .eq("published", true)
        .eq("category", blog.category)
        .neq("id", blog.id)
        .not("slug", "is", null)
        .order("published_at", {
          ascending: false,
          nullsFirst: false,
        })
        .limit(6);

    if (error) {
      console.error(
        "Failed to fetch related blogs:",
        error.message
      );

      return [];
    }

    return data ?? [];
  } catch (error) {
    console.error(
      "Unexpected related blogs error:",
      error
    );

    return [];
  }
}

