export async function generateMetadata(
  {
    params,
  }: {
    params: Promise<{ slug: string }>;
  }
): Promise<Metadata> {
  const { slug } = await params;

  const blog = await getBlog(slug);

  if (!blog) {
    return {
      title: "Article Not Found | AnantaGo",

      description:
        "The requested article could not be found.",

      robots: {
        index: false,
        follow: false,
      },
    };
  }

  const title =
    normalizeText(blog.meta_title) ||
    normalizeText(blog.title) ||
    "AnantaGo";

  const description =
    normalizeText(
      blog.meta_description
    ) ||
    normalizeText(blog.excerpt) ||
    normalizeText(blog.introduction) ||
    "Read the latest technology news, guides, explainers, app tips, AI updates and security advice on AnantaGo.";

  const canonicalUrl =
    `${BASE_URL}/blog/${encodeURIComponent(
      blog.slug
    )}`;

  const imageUrl = blog.cover_image
    ? absoluteUrl(blog.cover_image)
    : `${BASE_URL}/favicon.png`;

  return {
    title,

    description,

    alternates: {
      canonical: canonicalUrl,
    },

    robots: {
      index: true,
      follow: true,
      nocache: false,

      googleBot: {
        index: true,
        follow: true,
        noimageindex: false,
        "max-video-preview": -1,
        "max-image-preview": "large",
        "max-snippet": -1,
      },
    },

    authors: blog.author
      ? [{ name: blog.author }]
      : [{ name: "AnantaGo" }],

    creator:
      blog.author || "AnantaGo",

    publisher: "AnantaGo",

    openGraph: {
      type: "article",

      url: canonicalUrl,

      siteName: "AnantaGo",

      title,

      description,

      locale: "en_IN",

      publishedTime:
        blog.published_at || undefined,

      modifiedTime:
        blog.updated_at ||
        blog.published_at ||
        blog.created_at ||
        undefined,

      authors: blog.author
        ? [blog.author]
        : ["AnantaGo"],

      section:
        blog.category || undefined,

      tags:
        blog.tags || undefined,

      images: [
        {
          url: imageUrl,
          width: 1200,
          height: 630,
          alt: blog.title,
        },
      ],
    },

    twitter: {
      card: "summary_large_image",

      title,

      description,

      images: [imageUrl],
    },
  };
}

/* =========================================================
   CONTENT BLOCK RENDERER
========================================================= */

function renderContentBlock(
  block: ContentBlock,
  index: number
) {
  const type =
    normalizeText(block.type).toLowerCase();

  const heading =
    normalizeText(block.heading) ||
    normalizeText(block.title);

  const text =
    normalizeText(block.text) ||
    normalizeText(block.content);

  const image =
    normalizeText(block.image) ||
    normalizeText(block.image_url) ||
    normalizeText(block.src) ||
    normalizeText(block.url);

  const imageAlt =
    normalizeText(block.alt) ||
    heading ||
    "AnantaGo article image";

  const caption =
    normalizeText(block.caption);

  const key =
    block.id || `content-block-${index}`;

  /* ========================================================
     HEADING BLOCK
  ======================================================== */

  if (
    type === "heading" ||
    type === "h2" ||
    type === "h3" ||
    type === "h4" ||
    type === "section"
  ) {
    const headingText =
      heading || text;

    if (!headingText) {
      return null;
    }

    const level =
      block.level ||
      (type === "h3"
        ? 3
        : type === "h4"
        ? 4
        : 2);

    if (level === 4) {
      return (
        <h4
          key={key}
          className="mt-8 mb-3 text-lg font-bold leading-7 tracking-tight text-gray-900 sm:text-xl"
        >
          {headingText}
        </h4>
      );
    }

    if (level === 3) {
      return (
        <h3
          key={key}
          className="mt-10 mb-4 text-xl font-bold leading-tight tracking-tight text-gray-950 sm:text-2xl"
        >
          {headingText}
        </h3>
      );
    }

    return (
      <h2
        key={key}
        className="mt-12 mb-5 text-2xl font-bold leading-tight tracking-tight text-gray-950 sm:text-3xl"
      >
        {headingText}
      </h2>
    );
  }

  /* ========================================================
     TEXT / PARAGRAPH
  ======================================================== */

  if (
    type === "text" ||
    type === "paragraph" ||
    type === "p" ||
    !type
  ) {
    if (!text) {
      return null;
    }

    /*
     * New rich-text blocks contain HTML.
     */

    if (containsHtml(text)) {
      return (
        <RichText
          key={key}
          html={text}
          className="
            article-rich-text
            my-5
            text-[17px]
            leading-8
            text-gray-700
            sm:text-lg
            sm:leading-9
          "
        />
      );
    }

    /*
     * Old articles contain plain text.
     *
     * Keep them working exactly as before.
     */

    return (
      <p
        key={key}
        className="my-5 text-[17px] leading-8 text-gray-700 sm:text-lg sm:leading-9"
      >
        {text}
      </p>
    );
  }

  /* ========================================================
     IMAGE
  ======================================================== */

  if (
    type === "image" ||
    image
  ) {
    if (!image) {
      return null;
    }

    return (
      <figure
        key={key}
        className="my-9 overflow-hidden rounded-2xl"
      >
        <img
          src={absoluteUrl(image)}
          alt={imageAlt}
          width={1200}
          height={675}
          loading="lazy"
          decoding="async"
          className="h-auto w-full object-cover"
        />

        {caption && (
          <figcaption className="mt-3 text-center text-sm leading-6 text-gray-500">
            {caption}
          </figcaption>
        )}
      </figure>
    );
  }

  /* ========================================================
     BULLET LIST
  ======================================================== */

  if (
    type === "bullet-list" ||
    type === "bullets" ||
    type === "unordered-list"
  ) {
    const items =
      block.items?.filter(
        (item) =>
          typeof item === "string" &&
          item.trim()
      ) || [];

    if (items.length === 0) {
      return null;
    }

    return (
      <ul
        key={key}
        className="my-7 list-disc space-y-3 pl-7 text-[17px] leading-8 text-gray-700 sm:text-lg"
      >
        {items.map(
          (item, itemIndex) => (
            <li
              key={itemIndex}
              className="pl-1"
            >
              {containsHtml(item) ? (
                <RichText html={item} />
              ) : (
                item
              )}
            </li>
          )
        )}
      </ul>
    );
  }

  /* ========================================================
     NUMBERED LIST
  ======================================================== */

  if (
    type === "numbered-list" ||
    type === "ordered-list"
  ) {
    const items =
      block.items?.filter(
        (item) =>
          typeof item === "string" &&
          item.trim()
      ) || [];

    if (items.length === 0) {
      return null;
    }

    return (
      <ol
        key={key}
        className="my-7 list-decimal space-y-3 pl-7 text-[17px] leading-8 text-gray-700 sm:text-lg"
      >
        {items.map(
          (item, itemIndex) => (
            <li
              key={itemIndex}
              className="pl-1"
            >
              {containsHtml(item) ? (
                <RichText html={item} />
              ) : (
                item
              )}
            </li>
          )
        )}
      </ol>
    );
  }

  /* ========================================================
     QUOTE
  ======================================================== */

  if (
    type === "quote" ||
    type === "blockquote"
  ) {
    if (!text) {
      return null;
    }

    return (
      <blockquote
        key={key}
        className="my-10 border-l-4 border-gray-900 bg-gray-50 px-6 py-6 sm:px-8"
      >
        {containsHtml(text) ? (
          <RichText
            html={text}
            className="text-lg font-medium italic leading-8 text-gray-800 sm:text-xl sm:leading-9"
          />
        ) : (
          <p className="text-lg font-medium italic leading-8 text-gray-800 sm:text-xl sm:leading-9">
            “{text}”
          </p>
        )}
      </blockquote>
    );
  }

  /* ========================================================
     CALLOUT
  ======================================================== */

  if (
    type === "callout" ||
    type === "note" ||
    type === "tip"
  ) {
    if (!text) {
      return null;
    }

    return (
      <aside
        key={key}
        className="my-9 rounded-2xl border border-gray-200 bg-gray-50 p-6 sm:p-7"
      >
        {heading && (
          <h3 className="mb-3 text-lg font-bold text-gray-900 sm:text-xl">
            {heading}
          </h3>
        )}

        {containsHtml(text) ? (
          <RichText
            html={text}
            className="text-base leading-8 text-gray-700 sm:text-lg"
          />
        ) : (
          <p className="text-base leading-8 text-gray-700 sm:text-lg">
            {text}
          </p>
        )}
      </aside>
    );
  }

  /* ========================================================
     INLINE / STANDALONE LINK
  ======================================================== */

  if (
    type === "link" ||
    type === "button"
  ) {
    const href =
      normalizeText(block.href) ||
      normalizeText(block.url);

    const label =
      normalizeText(block.label) ||
      heading ||
      text ||
      "Read more";

    if (!href) {
      return null;
    }

    if (href.startsWith("/")) {
      return (
        <div
          key={key}
          className="my-6"
        >
          <Link
            href={href}
            className="font-semibold text-blue-600 underline decoration-blue-300 underline-offset-4 transition hover:text-blue-700 hover:decoration-blue-500"
          >
            {label}
          </Link>
        </div>
      );
    }

    return (
      <div
        key={key}
        className="my-6"
      >
        <a
          href={href}
          target="_blank"
          rel="noopener noreferrer"
          className="font-semibold text-blue-600 underline decoration-blue-300 underline-offset-4 transition hover:text-blue-700 hover:decoration-blue-500"
        >
          {label}
        </a>
      </div>
    );
  }

  /* ========================================================
     TABLE
  ======================================================== */

  if (type === "table") {
    const headers =
      block.headers || [];

    const rows =
      block.rows || [];

    if (
      headers.length === 0 &&
      rows.length === 0
    ) {
      return null;
    }

    return (
      <div
        key={key}
        className="my-9 overflow-hidden rounded-2xl border border-gray-200"
      >
        <div className="overflow-x-auto">
          <table className="min-w-[600px] w-full border-collapse text-sm sm:text-base">
            {headers.length > 0 && (
              <thead>
                <tr className="bg-gray-50">
                  {headers.map(
                    (
                      header,
                      headerIndex
                    ) => (
                      <th
                        key={
                          headerIndex
                        }
                        className="border-b border-gray-200 px-4 py-4 text-left font-bold text-gray-950"
                      >
                        {header}
                      </th>
                    )
                  )}
                </tr>
              </thead>
            )}

            <tbody>
              {rows.map(
                (
                  row,
                  rowIndex
                ) => (
                  <tr
                    key={rowIndex}
                    className="border-b border-gray-100 last:border-b-0"
                  >
                    {row.map(
                      (
                        cell,
                        cellIndex
                      ) => (
                        <td
                          key={
                            cellIndex
                          }
                          className="px-4 py-4 leading-7 text-gray-700"
                        >
                          {cell}
                        </td>
                      )
                    )}
                  </tr>
                )
              )}
            </tbody>
          </table>
        </div>
      </div>
    );
  }

  /* ========================================================
     DEFAULT FALLBACK
  ======================================================== */

  if (!text) {
    return null;
  }

  if (containsHtml(text)) {
    return (
      <RichText
        key={key}
        html={text}
        className="my-5 text-[17px] leading-8 text-gray-700 sm:text-lg sm:leading-9"
      />
    );
  }

  return (
    <p
      key={key}
      className="my-5 text-[17px] leading-8 text-gray-700 sm:text-lg sm:leading-9"
    >
      {text}
    </p>
  );
}

